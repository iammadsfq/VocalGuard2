    "def get_linear_filterbank(n_filters=20, n_fft=512, sr=16000, low_freq=0.0, high_freq=None):\n"
    "    if high_freq is None:\n"
    "        high_freq = sr / 2.0\n"
    "    freq_points = np.linspace(low_freq, high_freq, n_filters + 2)\n"
    "    bin_points = np.floor((n_fft + 1) * freq_points / sr).astype(int)\n"
    "    n_bins = n_fft // 2 + 1\n"
    "    filterbank = np.zeros((n_filters, n_bins))\n"
    "    for i in range(n_filters):\n"
    "        left, center, right = bin_points[i], bin_points[i + 1], bin_points[i + 2]\n"
    "        if center > left:\n"
    "            for b in range(left, center):\n"
    "                if b < n_bins:\n"
    "                    filterbank[i, b] = (b - left) / (center - left)\n"
    "        if right > center:\n"
    "            for b in range(center, right):\n"
    "                if b < n_bins:\n"
    "                    filterbank[i, b] = (right - b) / (right - center)\n"
    "    return filterbank\n"
    "\n"
    "FBANK_CACHE = get_linear_filterbank(20, 512, 16000)\n"
    "\n"
    "def compute_deltas(feats, N=2):\n"
    "    T, D = feats.shape\n"
    "    deltas = np.zeros_like(feats)\n"
    "    denom = 2 * sum(n**2 for n in range(1, N + 1))\n"
    "    for t in range(T):\n"
    "        num = np.zeros(D)\n"
    "        for n in range(1, N + 1):\n"
    "            t_plus = min(T - 1, t + n)\n"
    "            t_minus = max(0, t - n)\n"
    "            num += n * (feats[t_plus] - feats[t_minus])\n"
    "        deltas[t] = num / denom\n"
    "    return deltas\n"
    "\n"
    "def extract_lfcc(y, sr=16000, window_ms=20.0, hop_ms=10.0, n_fft=512, num_filters=20, num_coeffs=20):\n"
    "    if y.ndim > 1:\n"
    "        y = np.mean(y, axis=1)\n"
    "    y = np.append(y[0], y[1:] - 0.97 * y[:-1])\n"
    "    frame_len = int(sr * window_ms / 1000.0)\n"
    "    hop_len = int(sr * hop_ms / 1000.0)\n"
    "    if len(y) < frame_len:\n"
    "        y = np.pad(y, (0, frame_len - len(y)))\n"
    "    num_frames = 1 + (len(y) - frame_len) // hop_len\n"
    "    shape = (num_frames, frame_len)\n"
    "    strides = (y.strides[0] * hop_len, y.strides[0])\n"
    "    frames = np.lib.stride_tricks.as_strided(y, shape=shape, strides=strides).copy()\n"
    "    frames *= np.hanning(frame_len)\n"
    "    mag_spec = np.abs(np.fft.rfft(frames, n=n_fft, axis=-1))\n"
    "    filter_energies = np.dot(mag_spec, FBANK_CACHE.T)\n"
    "    log_energies = np.log(filter_energies + 1e-12)\n"
    "    static_lfcc = dct(log_energies, type=2, axis=-1, norm='ortho')[:, :num_coeffs]\n"
    "    delta = compute_deltas(static_lfcc, N=2)\n"
    "    delta2 = compute_deltas(delta, N=2)\n"
    "    return np.hstack([static_lfcc, delta, delta2])\n"
    "\n"
    "def trim_silence_energy(audio, frame_len=320, hop_len=160, top_db=30.0):\n"
    "    \"\"\"Pangkas segmen hening di awal/akhir dan sela-sela berdasarkan ambang dB relatif terhadap energi puncak.\"\"\"\n"
    "    if len(audio) < frame_len:\n"
    "        return audio\n"
    "    num_frames = 1 + (len(audio) - frame_len) // hop_len\n"
    "    shape = (num_frames, frame_len)\n"
    "    strides = (audio.strides[0] * hop_len, audio.strides[0])\n"
    "    frames = np.lib.stride_tricks.as_strided(audio, shape=shape, strides=strides)\n"
    "    rms = np.sqrt(np.mean(frames ** 2, axis=-1) + 1e-12)\n"
    "    ref = np.max(rms)\n"
    "    if ref <= 1e-6:\n"
    "        return audio\n"
    "    db = 20.0 * np.log10(rms / ref)\n"
    "    active_frames = np.where(db > -top_db)[0]\n"
    "    if len(active_frames) == 0:\n"
    "        return audio\n"
    "    start_sample = active_frames[0] * hop_len\n"
    "    end_sample = min(len(audio), active_frames[-1] * hop_len + frame_len)\n"
    "    trimmed = audio[start_sample:end_sample]\n"
    "    return trimmed if len(trimmed) >= frame_len else audio\n"
    "\n"
    "def pad_or_truncate(audio, target_length=64000):\n"
    "    length = len(audio)\n"
    "    if length == 0:\n"
    "        return np.zeros(target_length, dtype=np.float32)\n"
    "    if length == target_length:\n"
    "        return audio\n"
    "    if length > target_length:\n"
    "        return audio[:target_length]\n"
    "    repeat_factor = int(np.ceil(target_length / length))\n"
    "    repeated = np.tile(audio, repeat_factor)\n"
    "    return repeated[:target_length]\n"
    "\n"
    "class ASVspoof2019Dataset(Dataset):\n"
    "    def __init__(self, df, audio_dir, target_length=64000, sr=16000, trim_silence=False):\n"
    "        self.df = df.reset_index(drop=True)\n"
